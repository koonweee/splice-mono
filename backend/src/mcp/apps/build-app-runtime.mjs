import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const sourceDir = dirname(fileURLToPath(import.meta.url));
const entryPoint = resolve(sourceDir, 'app-runtime.ts');
const outputPath = resolve(sourceDir, 'app-runtime.generated.ts');

const result = await build({
  entryPoints: [entryPoint],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['es2022'],
  minify: true,
  legalComments: 'none',
  sourcemap: false,
  treeShaking: true,
  write: false,
  conditions: ['browser', 'import', 'default'],
});

const bundle = result.outputFiles[0]?.text;
if (!bundle) {
  throw new Error('MCP App runtime bundle was empty');
}

const inlineSafeBundle = bundle
  .replace(/<\/script/gi, '<\\/script')
  .replace(/\u2028/g, '\\u2028')
  .replace(/\u2029/g, '\\u2029');
const serializedBundle = JSON.stringify(inlineSafeBundle);

await writeFile(
  outputPath,
  `/* Generated by build-app-runtime.mjs. Do not edit. */\n/* eslint-disable */\nexport const MCP_APP_RUNTIME_SCRIPT = ${serializedBundle};\n`,
  'utf8',
);
